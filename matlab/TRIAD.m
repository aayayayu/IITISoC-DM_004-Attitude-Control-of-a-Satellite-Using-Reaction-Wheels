function [estimated_Abi] = TRIAD(t,orbit,rot)
tu2 = t/0.05;
tu = round(tu2,0);
T = tu+ 40000;
current_pos_xyz = orbit(T,:);
current_pos_xyz = current_pos_xyz/norm(current_pos_xyz);
theta = asind(current_pos_xyz(3));
LST = atan2d(current_pos_xyz(2), current_pos_xyz(1));% range:[0,pi/2]
Re = 6.37814e+3; 
Y = 2026;
M = 3;
D = 20;
s=t;
m=0;
h=0;
m = floor(s / 60);
s = mod(s, 60);
h = floor(m / 60);
m = mod(m, 60);
JD = 367*Y - floor((7/4)*(Y+floor((M+9)/12))) + floor(275*M/9) + D + 1721013.5;
Tut1 = (JD-2541545.0)/36525;
theta_gmst = 24110.54841+ 8640184.812866*Tut1+ 0.093104*(Tut1).^2 - 6.2*(10.^-6)*(Tut1.^3) + 1.002737909350795*(3600*h + 60*m+s);
theta_gmst = theta_gmst - 86400*(floor(theta_gmst/86400));
theta_gmst = theta_gmst/240;
phi = 360 + (LST-theta_gmst);
phi = mod(phi, 360); % Normalize phi to the range [0, 360]
m_vector = m_vector_ECI(Re,theta,phi,9574,Y,M,D,h,m,s);
s_vector= Sun_vector_ECI(Y,M,D,h,m,s);
sensor_m_data = magnetometer_sensor(Re,theta,phi,9574,Y,M,D,h,m,s,rot);
sensor_s_data = Sun_sensor(Y,M,D,h,m,s,rot);
t1_B = sensor_s_data;
t2_B = cross(sensor_s_data,sensor_m_data)/norm(cross(sensor_s_data,sensor_m_data));
t3_B = cross(t1_B,t2_B)/norm(cross(t1_B,t2_B));
Abt = [t1_B' t2_B' t3_B'];
t1_N = s_vector;
t2_N = cross(s_vector,m_vector)/norm(cross(s_vector,m_vector));
t3_N = cross(t1_N,t2_N)/norm(cross(t1_N,t2_N));
Ant = [t1_N' t2_N' t3_N'];
estimated_Abi = Abt * Ant'; % Calculate the estimated attitude using the transformation
