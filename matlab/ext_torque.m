function [tor_vec] = ext_torque(t,orbit,rot)
Y = 2026;
M = 3;
D = 20;
s=t;
m=0;
h=0;
m = floor(s / 60);
s = mod(s, 60);
h = floor(m / 60);
m = mod(m, 60);
net_torque = zeros(1,3);
surface_area = 3.1584e-6;
N=4;
n1_b = [1 0 0];
n2_b = [0 1 0];
n3_b = [-1 0 0];
n4_b = [0 -1 0];
n_b = [n1_b;n2_b;n3_b;n4_b];
r1_b = [-0.05 0.1 0];
r2_b = [-0.1 -0.05 0];
r3_b = [0.05 -0.1 0];
r4_b = [0.1 0.05 0];
r_b  = [r1_b;r2_b;r3_b;r4_b];
s_ECI = Sun_vector_ECI(Y,M,D,h,m,s);
s_vec = rot*s_ECI';
s_vec = s_vec';
w = 0.000072921158553;
tu2 = t/0.05;
tu = round(tu2,0);
T = tu+ 40000;
dR = 20.*(orbit(T+1,:) - orbit(T,:));
dr = rot*dR';
dr= dr';
vrel_b=[dr(1)+(w*orbit(T,2)),dr(2)-(w*orbit(T,1)),dr(3)];
for i = 1:N
    cos_aero= dot(n_b(i,:),vrel_b)/norm(vrel_b);
    cos_srp = dot(n_b(i,:),s_vec);
    u = max(cos_aero,0);
    u2 = max(cos_srp,0);
    F_aero = (-0.5*u*norm(vrel_b)*6e-13*1000*2.2).*vrel_b;
    F_srp = (-4.54e-6*surface_area*u2*1000).*((2*(0.04+0.18*cos_srp).*n_b(i,:))+(0.82.*s_vec));
    L_aero = cross(r_b(i,:),F_aero);
    L_srp = cross(r_b(i,:),F_srp);
    net_torque = net_torque + L_aero+L_srp;
end
rand_tor = zeros(1, 3); % Initialize the estimated_Abi matrix
for r = 1:3
        a = -0.02;
        b = 0.03;
        n = 1;
        t = a + (b-a).*rand(n,1);
        rand_tor(1,r) = t*1e-6;
end

tor_vec = net_torque +rand_tor;